// Generates the TypeScript design tokens for code that can't read CSS variables: the share and
// Stories cards (next/og) and the HTML emails. Run after changing design-system/design-tokens.json
// or the brand fonts or logo mark:
//
//   npm run tokens --workspace=@sunset/web
//
// Writes (all committed; CI fails if they're out of date):
//   apps/web/src/lib/design-tokens.generated.ts  colours (dark and light), spacing, radius, sizes
//   apps/web/src/lib/og-assets.generated.ts      brand fonts (base64 TTF) and the logo mark (SVG)
//   apps/web/public/brand/                       copies of the logo files the app serves
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const read = (path) => readFile(new URL(path, root));
const tokens = JSON.parse(await read("design-system/design-tokens.json"));

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const values = (group) =>
  Object.fromEntries(Object.entries(group).filter(([k]) => !k.startsWith("$")).map(([k, v]) => [camel(k), v.$value]));
const px = (group) => Object.fromEntries(Object.entries(values(group)).map(([k, v]) => [k, Number.parseFloat(v)]));
const unprefix = (obj, prefix) =>
  Object.fromEntries(Object.entries(obj).map(([k, v]) => [k.slice(prefix.length, prefix.length + 1).toLowerCase() + k.slice(prefix.length + 1), v]));

const header = (what) =>
  `// GENERATED by scripts/generate-tokens.mjs from ${what}. Do not edit by hand; run\n// \`npm run tokens --workspace=@sunset/web\` instead.\n`;

const tokenModule = `${header("design-system/design-tokens.json")}
export const colors = ${JSON.stringify({ dark: values(tokens.color.dark), light: values(tokens.color.light) }, null, 2)} as const;

export type ColorRole = keyof typeof colors.dark;

/** Sizes in px. */
export const spacing = ${JSON.stringify(unprefix(px(tokens.spacing), "space"), null, 2)} as const;
export const radius = ${JSON.stringify(unprefix(px(tokens.radius), "radius"), null, 2)} as const;
export const size = ${JSON.stringify(px(tokens.size), null, 2)} as const;

export const fontFamily = ${JSON.stringify(values(tokens.fontFamily), null, 2)} as const;
`;
await writeFile(new URL("apps/web/src/lib/design-tokens.generated.ts", root), tokenModule);

const fonts = [
  ["frauncesRegular", "Fraunces-Regular.ttf"],
  ["frauncesSemiBold", "Fraunces-SemiBold.ttf"],
  ["atkinsonRegular", "AtkinsonHyperlegible-Regular.ttf"],
  ["atkinsonBold", "AtkinsonHyperlegible-Bold.ttf"],
];
let assets = `${header("design-system/fonts and brand/logo")}
// next/og (Satori) needs font files as bytes; on Workers there's no file system to read them
// from, so they're embedded here.
`;
for (const [name, file] of fonts) {
  assets += `\n/** design-system/fonts/${file} */\nexport const ${name}Base64 =\n  "${(await read(`design-system/fonts/${file}`)).toString("base64")}";\n`;
}
const mark = (await read("brand/logo/sunset-soul-mark-for-dark-backgrounds.svg")).toString("utf8").trim();
assets += `\n/** brand/logo/sunset-soul-mark-for-dark-backgrounds.svg (viewBox ${mark.match(/viewBox="([^"]+)"/)[1]}) */\nexport const markForDarkBackgroundsSvg = ${JSON.stringify(mark)};\n`;
await writeFile(new URL("apps/web/src/lib/og-assets.generated.ts", root), assets);

// The logo files the app and emails serve, copied from the logo kit so they never drift.
const servedLogos = [
  "sunset-soul-logo-horizontal-transparent-for-dark-backgrounds.svg",
  "sunset-soul-logo-horizontal-transparent-for-light-backgrounds.svg",
  "sunset-soul-logo-horizontal-transparent-for-light-backgrounds.png",
  "sunset-soul-logo-stacked-transparent-for-dark-backgrounds.svg",
  "sunset-soul-logo-stacked-transparent-for-light-backgrounds.svg",
];
await mkdir(new URL("apps/web/public/brand/", root), { recursive: true });
for (const file of servedLogos) {
  await copyFile(new URL(`brand/logo/${file}`, root), new URL(`apps/web/public/brand/${file}`, root));
}

console.log("Wrote design-tokens.generated.ts, og-assets.generated.ts and public/brand/");
